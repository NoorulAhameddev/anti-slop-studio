function ColorSwatch({ color, label }) {
  return (
    <div style={{ display: 'flex', alignItems: 'center', gap: '0.5rem' }}>
      <div style={{
        width: '24px',
        height: '24px',
        borderRadius: '2px',
        background: color,
        border: '1px solid rgba(255,255,255,0.1)',
        flexShrink: 0,
      }} />
      <span style={{ fontFamily: 'var(--font-mono)', fontSize: '0.62rem', color: 'var(--ink-500)' }}>
        {label}: <span style={{ color: 'var(--ink-300)' }}>{color}</span>
      </span>
    </div>
  );
}

function generateArtBible(theme, brand, mood) {
  const t = theme;
  return `# Design System — ${brand || 'Your Brand'}
*Generated by Anti-Slop Studio · ${new Date().toLocaleDateString()}*

---

## Identity
- **Theme:** ${t.label}
- **Mood:** ${mood}
- **Personality:** ${t.personality}

---

## Color Palette

| Token      | Value       | Usage |
|------------|-------------|-------|
| Background | \`${t.palette.bg}\`  | Page base, never use slate-900 |
| Surface    | \`${t.palette.surface}\` | Panels, modals |
| Text Primary | \`${t.palette.text}\` | Headlines, body |
| Text Muted | \`${t.palette.muted}\`  | Secondary, captions |
| Accent     | \`${t.palette.accent}\`  | CTAs, highlights |
| Accent Dim | \`${t.palette.accent2}\` | Hover states |

> ⚠️ **Never use Tailwind's indigo-500, purple-500, or any purple/indigo gradient.** These are statistical defaults AI falls back to. Forbidden.

---

## Typography

\`\`\`css
:root {
  --font-display: ${t.fonts.display};
  --font-body:    ${t.fonts.body};
  --font-mono:    ${t.fonts.mono};
}
\`\`\`

| Role | Font | Size | Weight |
|------|------|------|--------|
| Hero H1 | Display | clamp(2.5rem, 7vw, 6rem) | 900 |
| Section H2 | Display | clamp(2rem, 4vw, 3rem) | 700 |
| Body | Body | 15–17px | 300–400 |
| Eyebrow | Mono | 0.65rem | 400 |
| Mono code | Mono | 0.72rem | 400 |

> Use letter-spacing: -0.03em on headings. Use letter-spacing: 0.12em on mono eyebrows.

---

## Spacing System (8px base)

\`\`\`
--space-1:  0.5rem   (8px)   — Icon gap
--space-2:  1rem     (16px)  — Inline element gap
--space-3:  1.5rem   (24px)  — Label to content
--space-4:  2rem     (32px)  — Component internal
--space-6:  3rem     (48px)  — Component gap
--space-8:  4rem     (64px)  — Section top padding
--space-12: 6rem     (96px)  — Major sections
--space-16: 8rem     (128px) — Hero padding
\`\`\`

**${t.spacing}**

---

## Motion

${t.motion}

\`\`\`css
/* Entrance animation — not bounce, not spin */
@keyframes fadeUp {
  from { opacity: 0; transform: translateY(20px); }
  to   { opacity: 1; transform: translateY(0); }
}

/* Stagger: add 0.12s delay per item */
.animate-item-1 { animation: fadeUp 0.7s cubic-bezier(0.16, 1, 0.3, 1) 0.12s forwards; }
.animate-item-2 { animation: fadeUp 0.7s cubic-bezier(0.16, 1, 0.3, 1) 0.24s forwards; }
\`\`\`

---

## Layout Rules

1. **No card overload.** Use left-border insets and negative space for hierarchy.
2. **No border everywhere.** One hairline color token. Use it sparingly.
3. **No glow blobs.** Use architectural grids or noise textures for background texture.
4. **No top-level clutter.** Maximum 2 primary CTAs. Hide secondary actions.
5. **Negative space is structural.** Padding is hierarchy. Don't fill everything.

---

## Anti-Slop Checklist

- [ ] No purple/indigo gradients
- [ ] No Inter font without deliberate choice
- [ ] No three-column feature card grid without editorial break
- [ ] No "Get Started" or "Learn More" CTAs
- [ ] No random glow circles in background
- [ ] No redundant subheadings ("Manage your X")
- [ ] No animate-bounce on elements
- [ ] No more than 2 primary actions visible at once

---

## Art Direction

Theme: **${t.label}**
Feed the following into every subsequent AI prompt to maintain consistency:

> Build the rest of the page maintaining the ${t.label} design system: background ${t.palette.bg}, accent ${t.palette.accent}, using ${t.fonts.display} for headings and ${t.fonts.body} for body. ${t.personality} personality. ${t.spacing}. ${t.motion}

---
*This Art Bible was generated by Anti-Slop Studio. Feed it into every Claude Code session.*
`;
}

export default function ArtBibleGenerator() {
  const [selectedTheme, setSelectedTheme] = useState(THEMES[0]);
  const [brand, setBrand] = useState('');
  const [mood, setMood] = useState('SaaS Platform');
  const [generated, setGenerated] = useState('');
  const [copied, setCopied] = useState(false);

  const generate = () => {
    const content = generateArtBible(selectedTheme, brand, mood);
    setGenerated(content);
  };

  const copyAll = () => {
    navigator.clipboard.writeText(generated).then(() => {
      setCopied(true);
      setTimeout(() => setCopied(false), 1800);
    });
  };

  const download = () => {
    const blob = new Blob([generated], { type: 'text/markdown' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `design-${(brand || 'brand').toLowerCase().replace(/\s/g, '-')}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div style={{
      borderTop: '1px solid var(--hair)',
      background: 'var(--ink-800)',
    }}>
      <div style={{ maxWidth: '1200px', margin: '0 auto', padding: '6rem 2rem' }}>

        {/* Section header */}
        <div style={{ marginBottom: '3rem' }}>
          <p className="eyebrow" style={{ marginBottom: '1rem' }}>Tool 02</p>
          <h2 style={{
            fontSize: 'clamp(2rem, 4vw, 3rem)',
            fontStyle: 'italic',
            fontWeight: 700,
            lineHeight: 1.1,
            marginBottom: '1rem',
          }}>
            Art Bible Generator
          </h2>
          <p style={{ color: 'var(--ink-400)', maxWidth: '52ch', lineHeight: 1.65, fontWeight: 300 }}>
            Generate a <code style={{ color: 'var(--brand)', background: 'var(--brand-glow)', padding: '0 4px', borderRadius: '2px' }}>design.md</code> art bible.
            Feed it to Claude Code at the start of every session to lock in your visual system
            and prevent AI from reverting to defaults.
          </p>
        </div>

        <div style={{
          display: 'grid',
          gridTemplateColumns: '1fr 1.4fr',
          gap: '3rem',
          alignItems: 'start',
        }}>
          {/* Controls */}
          <div style={{ display: 'flex', flexDirection: 'column', gap: '2rem' }}>

            {/* Brand name */}
            <div className="field">
              <label>Brand / Project Name</label>
              <input
                type="text"
                value={brand}
                onChange={e => setBrand(e.target.value)}
                placeholder="e.g. Argus, Obsidian Vault…"
              />
            </div>

            {/* Mood */}
            <div className="field">
              <label>Project Type</label>
              <select value={mood} onChange={e => setMood(e.target.value)}>
                {MOODS.map(m => <option key={m}>{m}</option>)}
              </select>
            </div>

            {/* Theme picker */}
            <div>
              <div style={{
                fontFamily: 'var(--font-mono)',
                fontSize: '0.62rem',
                letterSpacing: '0.12em',
                textTransform: 'uppercase',
                color: 'var(--ink-400)',
                marginBottom: '0.75rem',
              }}>Visual Direction</div>
              <div style={{ display: 'flex', flexDirection: 'column', gap: '0' }}>
                {THEMES.map(theme => (
                  <button
                    key={theme.id}
                    onClick={() => setSelectedTheme(theme)}
                    style={{
                      display: 'flex',
                      justifyContent: 'space-between',
                      alignItems: 'center',
                      padding: '1rem',
                      background: selectedTheme.id === theme.id
                        ? 'rgba(200,150,90,0.06)'
                        : 'transparent',
                      border: 'none',
                      borderLeft: `2px solid ${selectedTheme.id === theme.id ? 'var(--brand)' : 'transparent'}`,
                      borderBottom: '1px solid var(--hair)',
                      cursor: 'pointer',
                      textAlign: 'left',
                      transition: 'all 0.15s ease',
                    }}
                  >
                    <div>
                      <div style={{
                        fontFamily: 'var(--font-mono)',
                        fontSize: '0.72rem',
                        color: selectedTheme.id === theme.id ? 'var(--brand)' : 'var(--ink-300)',
                        letterSpacing: '0.06em',
                        textTransform: 'uppercase',
                      }}>{theme.label}</div>
                      <div style={{
                        fontSize: '0.78rem',
                        color: 'var(--ink-500)',
                        marginTop: '0.25rem',
                        fontWeight: 300,
                      }}>{theme.description}</div>
                    </div>
                    {/* Palette preview */}
                    <div style={{ display: 'flex', gap: '3px', flexShrink: 0, marginLeft: '1rem' }}>
                      {Object.values(theme.palette).slice(0, 4).map((col, i) => (
                        <div key={i} style={{
                          width: '12px',
                          height: '12px',
                          borderRadius: '50%',
                          background: col,
                        }} />
                      ))}
                    </div>
                  </button>
                ))}
              </div>
            </div>

            {/* Selected theme palette */}
            {selectedTheme && (
              <div style={{
                padding: '1.25rem',
                background: 'var(--ink-900)',
                border: '1px solid var(--hair)',
                borderRadius: '2px',
              }}>
                <div style={{
                  fontFamily: 'var(--font-mono)',
                  fontSize: '0.62rem',
                  letterSpacing: '0.12em',
                  textTransform: 'uppercase',
                  color: 'var(--ink-500)',
                  marginBottom: '0.75rem',
                }}>Palette Preview</div>
                <div style={{ display: 'flex', flexDirection: 'column', gap: '0.375rem' }}>
                  {Object.entries(selectedTheme.palette).map(([key, val]) => (
                    <ColorSwatch key={key} color={val} label={key} />
                  ))}
                </div>
              </div>
            )}

            <button className="btn-primary" onClick={generate} style={{ alignSelf: 'flex-start' }}>
              Generate Art Bible <span className="arrow">→</span>
            </button>
          </div>

          {/* Output */}
          <div>
            {!generated ? (
              <div style={{
                height: '500px',
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'center',
                border: '1px dashed var(--hair)',
                borderRadius: '2px',
                flexDirection: 'column',
                gap: '1rem',
              }}>
                <span style={{
                  fontFamily: 'var(--font-display)',
                  fontStyle: 'italic',
                  fontSize: '2rem',
                  color: 'var(--ink-700)',
                }}>design.md</span>
                <span style={{
                  fontFamily: 'var(--font-mono)',
                  fontSize: '0.62rem',
                  color: 'var(--ink-600)',
                  letterSpacing: '0.12em',
                  textTransform: 'uppercase',
                }}>Will appear here</span>
              </div>
            ) : (
              <div style={{ animation: 'fadeIn 0.4s ease' }}>
                <div style={{
                  display: 'flex',
                  justifyContent: 'space-between',
                  alignItems: 'center',
                  marginBottom: '0.75rem',
                  gap: '1rem',
                }}>
                  <span style={{
                    fontFamily: 'var(--font-mono)',
                    fontSize: '0.62rem',
                    color: 'var(--good)',
                    letterSpacing: '0.1em',
                    textTransform: 'uppercase',
                  }}>✓ design.md ready</span>
                  <div style={{ display: 'flex', gap: '0.5rem' }}>
                    <button
                      className={`copy-btn ${copied ? 'copied' : ''}`}
                      onClick={copyAll}
                    >{copied ? '✓ Copied' : 'Copy All'}</button>
                    <button className="copy-btn" onClick={download}>Download .md</button>
                  </div>
                </div>
                <pre className="code-area" style={{
                  whiteSpace: 'pre-wrap',
                  wordBreak: 'break-word',
                  height: '500px',
                  overflowY: 'auto',
                  resize: 'none',
                  fontSize: '0.68rem',
                }}>{generated}</pre>
              </div>
            )}
          </div>
        </div>
      </div>
    </div>
  );
}
